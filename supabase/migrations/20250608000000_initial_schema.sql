-- Helper: is admin
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT COALESCE(
    (SELECT is_admin FROM public.profiles WHERE id = auth.uid()),
    false
  );
$$;

-- Categories: public read
DROP POLICY IF EXISTS categories_select ON public.categories;
CREATE POLICY categories_select ON public.categories FOR SELECT TO anon, authenticated USING (true);

-- Profiles
DROP POLICY IF EXISTS profiles_select_own ON public.profiles;
CREATE POLICY profiles_select_own ON public.profiles FOR SELECT TO authenticated
  USING (id = auth.uid() OR public.is_admin());

DROP POLICY IF EXISTS profiles_update_own ON public.profiles;
CREATE POLICY profiles_update_own ON public.profiles FOR UPDATE TO authenticated
  USING (id = auth.uid()) WITH CHECK (id = auth.uid());

-- Duas: public read published only
DROP POLICY IF EXISTS duas_select_published ON public.duas;
CREATE POLICY duas_select_published ON public.duas FOR SELECT TO anon, authenticated
  USING (published = true OR public.is_admin());

-- Dua prayers: users read own
DROP POLICY IF EXISTS dua_prayers_select_own ON public.dua_prayers;
CREATE POLICY dua_prayers_select_own ON public.dua_prayers FOR SELECT TO authenticated
  USING (user_id = auth.uid() OR public.is_admin());

-- Grant execute on RPCs
GRANT EXECUTE ON FUNCTION public.pray_for_dua(bigint, text) TO anon, authenticated;
GRANT EXECUTE ON FUNCTION public.increment_likes(bigint) TO anon, authenticated;
