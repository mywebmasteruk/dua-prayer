-- DuaPrayer community domain (feed, share dua, ameen)
-- Coexists with Makerkit accounts; uses public.is_super_admin() for elevated reads.

-- Categories (topics now; channel columns reserved for later port)
CREATE TABLE IF NOT EXISTS public.categories (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE,
  description text NOT NULL DEFAULT '',
  is_active boolean NOT NULL DEFAULT true,
  sort_order integer NOT NULL DEFAULT 0,
  channel_type text NOT NULL DEFAULT 'category'
    CHECK (channel_type IN ('category', 'user')),
  status text NOT NULL DEFAULT 'approved'
    CHECK (status IN ('approved', 'pending_review', 'rejected')),
  owner_id uuid REFERENCES auth.users (id) ON DELETE SET NULL,
  handle text UNIQUE,
  is_verified boolean NOT NULL DEFAULT false,
  verified_at timestamptz,
  reviewed_at timestamptz,
  reviewed_by uuid REFERENCES auth.users (id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS categories_active_status_idx
  ON public.categories (is_active, status, sort_order, name);

-- Duas
CREATE TABLE IF NOT EXISTS public.duas (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  text text NOT NULL CHECK (char_length(text) >= 15 AND char_length(text) <= 1200),
  user_id uuid REFERENCES auth.users (id) ON DELETE SET NULL,
  category_id bigint REFERENCES public.categories (id) ON DELETE SET NULL,
  channel_id bigint REFERENCES public.categories (id) ON DELETE SET NULL,
  likes integer NOT NULL DEFAULT 0 CHECK (likes >= 0),
  published boolean NOT NULL DEFAULT true,
  flagged boolean NOT NULL DEFAULT false,
  language text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS duas_published_created_idx
  ON public.duas (published, created_at DESC);

CREATE INDEX IF NOT EXISTS duas_category_idx ON public.duas (category_id);

CREATE INDEX IF NOT EXISTS duas_channel_idx ON public.duas (channel_id);

CREATE INDEX IF NOT EXISTS duas_flagged_idx ON public.duas (flagged)
  WHERE flagged = true;

-- Ameen / prayer dedupe
CREATE TABLE IF NOT EXISTS public.dua_prayers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dua_id bigint NOT NULL REFERENCES public.duas (id) ON DELETE CASCADE,
  user_id uuid REFERENCES auth.users (id) ON DELETE CASCADE,
  voter_hash text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT dua_prayers_voter_check CHECK (
    user_id IS NOT NULL
    OR voter_hash IS NOT NULL
  )
);

CREATE UNIQUE INDEX IF NOT EXISTS dua_prayers_user_unique
  ON public.dua_prayers (dua_id, user_id)
  WHERE user_id IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS dua_prayers_hash_unique
  ON public.dua_prayers (dua_id, voter_hash)
  WHERE voter_hash IS NOT NULL;

CREATE INDEX IF NOT EXISTS dua_prayers_user_id_idx ON public.dua_prayers (user_id);

CREATE INDEX IF NOT EXISTS dua_prayers_voter_hash_idx ON public.dua_prayers (voter_hash);

