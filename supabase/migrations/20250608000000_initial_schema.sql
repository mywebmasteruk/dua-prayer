-- Auto-create profile on signup
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  INSERT INTO public.profiles (id, display_name)
  VALUES (NEW.id, COALESCE(NEW.raw_user_meta_data->>'display_name', split_part(NEW.email, '@', 1)))
  ON CONFLICT (id) DO NOTHING;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- Pray RPC: dedupe via dua_prayers, increment likes
CREATE OR REPLACE FUNCTION public.pray_for_dua(p_dua_id bigint, p_voter_hash text DEFAULT NULL)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_user_id uuid := auth.uid();
  v_hash text;
  v_inserted boolean := false;
BEGIN
  IF p_dua_id IS NULL THEN
    RETURN jsonb_build_object('success', false, 'error', 'invalid_dua');
  END IF;

  IF NOT EXISTS (SELECT 1 FROM public.duas WHERE id = p_dua_id AND published = true) THEN
    RETURN jsonb_build_object('success', false, 'error', 'not_found');
  END IF;

  IF v_user_id IS NOT NULL THEN
    INSERT INTO public.dua_prayers (dua_id, user_id)
    VALUES (p_dua_id, v_user_id)
    ON CONFLICT DO NOTHING;
    GET DIAGNOSTICS v_inserted = ROW_COUNT;
    IF v_inserted THEN
      UPDATE public.duas SET likes = likes + 1 WHERE id = p_dua_id;
    END IF;
  ELSIF p_voter_hash IS NOT NULL AND length(p_voter_hash) >= 16 THEN
    v_hash := p_voter_hash;
    INSERT INTO public.dua_prayers (dua_id, voter_hash)
    VALUES (p_dua_id, v_hash)
    ON CONFLICT DO NOTHING;
    GET DIAGNOSTICS v_inserted = ROW_COUNT;
    IF v_inserted THEN
      UPDATE public.duas SET likes = likes + 1 WHERE id = p_dua_id;
    END IF;
  ELSE
    RETURN jsonb_build_object('success', false, 'error', 'unauthorized');
  END IF;

  RETURN jsonb_build_object(
    'success', true,
    'counted', v_inserted,
    'likes', (SELECT likes FROM public.duas WHERE id = p_dua_id)
  );
END;
$$;

-- Legacy RPC name used by prototype
CREATE OR REPLACE FUNCTION public.increment_likes(dua_id bigint)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  PERFORM public.pray_for_dua(dua_id, NULL);
END;
$$;

