-- DuaPrayer production schema
-- Apply via Supabase Dashboard → SQL Editor, or: supabase db push

-- Categories
CREATE TABLE IF NOT EXISTS public.categories (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- Profiles (admin flag in app_metadata-safe column)
CREATE TABLE IF NOT EXISTS public.profiles (
  id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  display_name text,
  is_admin boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- Upgrade existing duas table from prototype
ALTER TABLE IF EXISTS public.duas ADD COLUMN IF NOT EXISTS published boolean NOT NULL DEFAULT true;
ALTER TABLE IF EXISTS public.duas ADD COLUMN IF NOT EXISTS flagged boolean NOT NULL DEFAULT false;

-- Duas
CREATE TABLE IF NOT EXISTS public.duas (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  text text NOT NULL CHECK (char_length(text) >= 15 AND char_length(text) <= 280),
  user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  category_id bigint REFERENCES public.categories(id) ON DELETE SET NULL,
  likes integer NOT NULL DEFAULT 0 CHECK (likes >= 0),
  published boolean NOT NULL DEFAULT true,
  flagged boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS duas_published_created_idx ON public.duas (published, created_at DESC);
CREATE INDEX IF NOT EXISTS duas_flagged_idx ON public.duas (flagged) WHERE flagged = true;
CREATE INDEX IF NOT EXISTS duas_category_idx ON public.duas (category_id);

-- Anonymous + authenticated pray deduplication
CREATE TABLE IF NOT EXISTS public.dua_prayers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dua_id bigint NOT NULL REFERENCES public.duas(id) ON DELETE CASCADE,
  user_id uuid REFERENCES auth.users(id) ON DELETE CASCADE,
  voter_hash text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT dua_prayers_voter_check CHECK (user_id IS NOT NULL OR voter_hash IS NOT NULL)
);

CREATE UNIQUE INDEX IF NOT EXISTS dua_prayers_user_unique ON public.dua_prayers (dua_id, user_id) WHERE user_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS dua_prayers_hash_unique ON public.dua_prayers (dua_id, voter_hash) WHERE voter_hash IS NOT NULL;

