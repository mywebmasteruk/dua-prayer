-- Ameen RPC
CREATE OR REPLACE FUNCTION public.pray_for_dua (
  p_dua_id bigint,
  p_voter_hash text DEFAULT NULL
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_user_id uuid := auth.uid();
  v_hash text;
  v_inserted boolean := false;
BEGIN
  IF p_dua_id IS NULL THEN
    RETURN jsonb_build_object('success', false, 'error', 'invalid_dua');
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM public.duas
    WHERE id = p_dua_id
      AND published = true
  ) THEN
    RETURN jsonb_build_object('success', false, 'error', 'not_found');
  END IF;

  IF v_user_id IS NOT NULL THEN
    INSERT INTO public.dua_prayers (dua_id, user_id)
    VALUES (p_dua_id, v_user_id)
    ON CONFLICT DO NOTHING;

    GET DIAGNOSTICS v_inserted = ROW_COUNT;

    IF v_inserted THEN
      UPDATE public.duas
      SET likes = likes + 1
      WHERE id = p_dua_id;
    END IF;
  ELSIF p_voter_hash IS NOT NULL AND length(p_voter_hash) >= 16 THEN
    v_hash := p_voter_hash;

    INSERT INTO public.dua_prayers (dua_id, voter_hash)
    VALUES (p_dua_id, v_hash)
    ON CONFLICT DO NOTHING;

    GET DIAGNOSTICS v_inserted = ROW_COUNT;

    IF v_inserted THEN
      UPDATE public.duas
      SET likes = likes + 1
      WHERE id = p_dua_id;
    END IF;
  ELSE
    RETURN jsonb_build_object('success', false, 'error', 'unauthorized');
  END IF;

  RETURN jsonb_build_object(
    'success', true,
    'counted', v_inserted,
    'likes', (SELECT likes FROM public.duas WHERE id = p_dua_id)
  );
END;
$$;

GRANT EXECUTE ON FUNCTION public.pray_for_dua (bigint, text) TO anon, authenticated, service_role;

-- RLS
ALTER TABLE public.categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.duas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.dua_prayers ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS categories_select_approved ON public.categories;
CREATE POLICY categories_select_approved ON public.categories
  FOR SELECT TO anon, authenticated
  USING (
    status = 'approved'
    OR public.is_super_admin()
  );

DROP POLICY IF EXISTS duas_select_published ON public.duas;
CREATE POLICY duas_select_published ON public.duas
  FOR SELECT TO anon, authenticated
  USING (
    published = true
    OR public.is_super_admin()
  );

DROP POLICY IF EXISTS dua_prayers_select_own ON public.dua_prayers;
CREATE POLICY dua_prayers_select_own ON public.dua_prayers
  FOR SELECT TO authenticated
  USING (
    user_id = auth.uid()
    OR public.is_super_admin()
  );

-- No INSERT/UPDATE/DELETE policies on duas: app uses service-role client.
GRANT SELECT ON public.categories TO anon, authenticated;
GRANT SELECT ON public.duas TO anon, authenticated;
GRANT SELECT ON public.dua_prayers TO authenticated;
